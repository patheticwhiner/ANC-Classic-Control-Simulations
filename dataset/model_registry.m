function item = empty_record()
item = struct( ...
    'id', '', ...
    'loader_id', '', ...
    'loader_type', '', ...
    'artifact', '', ...
    'role', '', ...
    'origin', '', ...
    'representation', '', ...
    'domain', '', ...
    'sample_rate', '', ...
    'source', '', ...
    'evidence', '', ...
    'consumers', '', ...
    'maturity', '', ...
    'notes', '');
end

function item = record(id, loaderId, loaderType, artifact, role, origin, ...
    representation, domain, sampleRate, source, evidence, consumers, ...
    maturity, notes)
item = empty_record();
item.id = id;
item.loader_id = loaderId;
item.loader_type = loaderType;
item.artifact = artifact;
item.role = role;
item.origin = origin;
item.representation = representation;
item.domain = domain;
item.sample_rate = sampleRate;
item.source = source;
item.evidence = evidence;
item.consumers = consumers;
item.maturity = maturity;
item.notes = notes;
end
