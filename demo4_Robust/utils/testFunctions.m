function f = testFunctions(x, obj_func)
% TESTFUNCTIONS 多目标标准测试函数（附录A）
%   用于验证 ε-MOPSO 算法的正确性。
%
%   输入:
%     x        - 决策变量向量 (列向量, n_var × 1), 所有分量 ∈ [0, 1]
%     func_num - 函数编号 (1-4)
%
%   输出:
%     f        - 目标函数值向量 (列向量, n_obj × 1)
%
%   参考文献:
%     Coello Coello, C.A., et al. "Evolutionary Algorithms for Solving
%     Multi-Objective Problems", 2nd Ed., Springer, 2007.  Appendix A.
%
%   F1 (A.1): 2目标, n=2, x₁∈[0,1], x₂∈[-30,30]
%     f₁ = x₁
%     f₂ = g·h
%     g  = 11 + x₂² - 10·cos(2π·x₂)
%     h  = 1 - √(f₁/g)  if f₁≤g else 0
%     Pareto前沿: f₂ = 1 - √f₁
%
%   F2 (A.2): 2目标, n=30, x∈[0,1]
%     f₁ = x₁
%     f₂ = g·h + 1
%     g  = 1 + 9/(n-1)·Σx(2:30)
%     h  = 1 - √(f₁/g) - (f₁/g)·sin(10π·f₁)
%     Pareto前沿 (g=1): f₂ = 2 - √f₁ - f₁·sin(10π·f₁)
%
%   F3 (A.3): 3目标, n=3, x∈[0,1]
%     f₁ = (1+x₃)·cos(πx₁/2)·cos(πx₂/2)
%     f₂ = (1+x₃)·cos(πx₁/2)·sin(πx₂/2)
%     f₃ = (1+x₃)·sin(πx₁/2)
%     Pareto前沿: 单位球面第一象限 (x₃=0, r=1)
%
%   F4 (A.4): 3目标, n=3, x∈[0,1]
%     f₁ = x₁
%     f₂ = x₂
%     f₃ = 3.5 - Σ 2xᵢ·sin(3π·xᵢ)
%     Pareto前沿: f₃_min(f₁,f₂) (非连续曲面)

    % =====================================================================
    % 输入参数验证
    % =====================================================================
    if nargin < 2
        error('testFunctions:NotEnoughInputs', ...
              '需要2个输入参数: x 和 func_num。');
    end

    % 确保 x 是列向量
    x = x(:);
    n = length(x);

    % 检查 x 是否在 [0,1] 范围内（允许微小容差）
    tol = 1e-8;
    if any(x < -tol) || any(x > 1 + tol)
        warning('testFunctions:OutOfBounds', ...
                '部分决策变量超出 [0,1] 范围，将被裁剪。');
        x = max(0, min(1, x));
    end

    % =====================================================================
    % 根据函数编号计算目标值
    % =====================================================================
    switch obj_func
        case 1
            % =============================================================
            % F1 (A.1): 2目标, n=2
            %   x₁ ∈ [0,1] 直接使用
            %   x₂ ∈ [0,1] → 映射到 [-30, 30]
            % =============================================================
            f1 = x(1);

            % 将 x(2) 从 [0,1] 映射到 [-30, 30]
            x2 = -30 + 60 * x(2);

            g = 11 + x2^2 - 10 * cos(2 * pi * x2);

            if f1 <= g
                h = 1 - sqrt(f1 / g);
            else
                h = 0;
            end
            f2 = g * h;

            f = [f1; f2];

        case 2
            % =============================================================
            % F2 (A.2): 2目标, n=30
            %   f₂ = g·h + 1  (原文公式)
            % =============================================================
            if n < 2
                error('testFunctions:InvalidDimension', ...
                      'F2 要求决策变量维度至少为2，当前维度为 %d。', n);
            end

            f1 = x(1);

            % g 函数 (原文: g = 1 + 9/(n-1)·Σx(2:30))
            g = 1 + 9 / (n - 1) * sum(x(2:end));

            % h 函数 (原文: h = 1 - √(f₁/g) - (f₁/g)·sin(10πf₁))
            h = 1 - sqrt(f1 / g) - (f1 / g) * sin(10 * pi * f1);

            % f₂ = g·h + 1 (原文)
            f2 = g * h + 1;

            f = [f1; f2];

        case 3
            % =============================================================
            % F3 (A.3): 3目标, n=3
            %   r = 1 + x₃ ∈ [1, 2]
            %   θ = πx₁/2 ∈ [0, π/2]
            %   φ = πx₂/2 ∈ [0, π/2]
            %   Pareto最优: x₃=0, r=1 → 单位球面第一象限
            % =============================================================
            if n < 3
                error('testFunctions:InvalidDimension', ...
                      'F3 要求决策变量维度至少为3，当前维度为 %d。', n);
            end

            r     = 1 + x(3);                       % r ∈ [1, 2]
            theta = pi * x(1) / 2;                   % θ ∈ [0, π/2]
            phi   = pi * x(2) / 2;                   % φ ∈ [0, π/2]

            f1 = r * cos(theta) * cos(phi);
            f2 = r * cos(theta) * sin(phi);
            f3 = r * sin(theta);

            f = [f1; f2; f3];

        case 4
            % =============================================================
            % F4 (A.4): 3目标, n=3
            %   f₃ = 3.5 - Σ 2xᵢ·sin(3πxᵢ)
            % =============================================================
            if n < 3
                error('testFunctions:InvalidDimension', ...
                      'F4 要求决策变量维度至少为3，当前维度为 %d。', n);
            end

            f1 = x(1);
            f2 = x(2);

            % f₃ = 3.5 - Σ 2xᵢ·sin(3πxᵢ)  (n=3)
            f3 = 3.5 - sum(2 * x .* sin(3 * pi * x));

            f = [f1; f2; f3];

        otherwise
            error('testFunctions:InvalidFuncNum', ...
                  '无效的函数编号 %d。有效范围: 1-4。', obj_func);
    end

end
