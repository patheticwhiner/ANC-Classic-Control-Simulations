function candidates = named_sweep(prefix, fieldName, values)
candidates = cell(numel(values), 1);
for index = 1:numel(values)
    params = struct();
    params.(fieldName) = values(index);
    candidates{index} = candidate(sprintf('%s_%g', prefix, values(index)), params);
end
end

function value = candidate(name, params)
value = struct('name', name, 'params', params);
end

function combined = merge_params(base, overrides)
combined = base;
fields = fieldnames(overrides);
for index = 1:numel(fields)
    combined.(fields{index}) = overrides.(fields{index});
end
end

function [feasible, stable] = is_feasible(result)
stable = stability_status(result);
feasible = stable ...
    && all(isfinite([result.supp_db, result.extra.u_demand_max])) ...
    && result.extra.u_demand_max <= 4 ...
    && result.extra.saturation_count == 0;
if strcmp(result.demo, 'demo5')
    feasible = feasible && result.extra.case_a_applicable;
end
end

function score = candidate_score(result, feasible, stable)
if ~all(isfinite([result.supp_db, result.extra.u_demand_max]))
    score = -inf;
    return;
end

score = result.supp_db ...
    - 8 * max(0, result.extra.u_demand_max - 4) ...
    - 0.02 * result.extra.saturation_count ...
    - 100 * double(~stable);
if feasible
    score = score + 1000;
end
end

