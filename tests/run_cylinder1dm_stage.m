function stage = run_cylinder1dm_stage(scope)
%RUN_CYLINDER1DM_STAGE Tune, freeze, and evaluate Demo1-5.
%
%   默认只运行 T1/T2 主实验。宽带 T3 使用
%   run_cylinder1dm_stage('broadband') 独立运行，避免其失败边界
%   干扰 fixed/adaptive 主比较的观察。
%
%   阶段流程全部在本文件内：候选调参 (tune_demo1234_controllers)、
%   冻结评价、Demo2 T2 的 RLS/LMS 对照 (compare_demo2_t2_adaptation)
%   都是局部函数，controller_demo1/2/3/4 与报告生成在 internal/。

if nargin < 1, scope = 'main'; end
scope = validatestring(scope, {'main', 'broadband'});

testDir = fileparts(mfilename('fullpath'));
run(fullfile(testDir, 'startup.m'));

% The loader validates the cached suite's path-family metadata and rebuilds
% it when the default model family changes (e.g. ARMAX -> measured FIR).
suite = load_cylinder1dm_signals('suite');

if strcmp(scope, 'main')
    outputDir = fullfile(testDir, 'output', 'cylinder1dm_2k', 'demo1234_stage');
    artifactPrefix = 'demo1234';
else
    outputDir = fullfile(testDir, 'output', 'cylinder1dm_2k', 'broadband_stage');
    artifactPrefix = 'broadband';
end
figureDir = fullfile(testDir, 'figures', 'cylinder1dm_2k');
if ~isfolder(outputDir), mkdir(outputDir); end
if ~isfolder(figureDir), mkdir(figureDir); end

[selections, tuningTable] = tune_demo1234_controllers(suite.calibration, scope);
evaluationResults = cell(numel(selections), 1);
summaryRows = cell(numel(selections), 14);

fprintf('\n========== Frozen held-out evaluation ==========' );
fprintf('\n');
for index = 1:numel(selections)
    selection = selections(index);
    runner = runner_for_demo(selection.demo);
    result = runner(suite.evaluation, selection.test, ...
        selection.variant, selection.params);
    evaluationResults{index} = result;

    [stable, stabilityValue] = stability_status(result);
    success = stable ...
        && result.supp_db >= 20 ...
        && result.extra.u_demand_max <= suite.meta.tuning_peak_limit ...
        && result.extra.saturation_count == 0;
    if strcmp(selection.demo, 'demo5')
        success = success && result.extra.case_a_applicable;
    end

    summaryRows(index, :) = {selection.demo, selection.variant, ...
        selection.test, selection.candidate, selection.feasible, success, ...
        selection.calibration_result.supp_db, result.supp_db, ...
        result.extra.u_demand_max, result.extra.saturation_count, stable, ...
        stabilityValue, result.u_rms, jsonencode(selection.params)};

    fprintf('  %-5s %-8s %s: %7.2f dB raw=%6.3f sat=%d success=%d\n', ...
        selection.demo, selection.variant, selection.test, result.supp_db, ...
        result.extra.u_demand_max, result.extra.saturation_count, success);
end

summary = cell2table(summaryRows, 'VariableNames', { ...
    'demo', 'variant', 'test', 'candidate', 'calibration_feasible', ...
    'evaluation_success', 'calibration_suppression_db', ...
    'evaluation_suppression_db', 'control_demand_max', ...
    'saturation_count', 'stable', 'stability_value', 'control_rms', ...
    'params_json'});

stage = struct();
stage.scope = scope;
stage.suite = suite;
stage.selections = selections;
stage.tuning = tuningTable;
stage.evaluation_results = evaluationResults;
stage.summary = summary;
stage.generated_at = datetime('now');

if strcmp(scope, 'main')
    demo2T2Index = find(strcmp({selections.demo}, 'demo2') ...
        & strcmp({selections.test}, 'T2'), 1);
    stage.demo2_t2_comparison = compare_demo2_t2_adaptation( ...
        suite.calibration, suite.evaluation, selections(demo2T2Index), ...
        evaluationResults{demo2T2Index});
end

stageFile = fullfile(outputDir, sprintf('%s_stage_results.mat', artifactPrefix));
save(stageFile, 'stage');
writetable(tuningTable, fullfile(outputDir, sprintf('%s_tuning.csv', artifactPrefix)));
writetable(summary, fullfile(outputDir, sprintf('%s_evaluation.csv', artifactPrefix)));

if strcmp(scope, 'main')
    writetable(stage.demo2_t2_comparison.tuning, ...
        fullfile(outputDir, 'demo2_t2_adaptation.csv'));
    generate_demo1234_reports(stage, figureDir, testDir, 'demo2', 't2');
    generate_demo1234_reports(stage, figureDir, testDir, '', 'report');
    if usejava('desktop')
        render_cylinder1dm();
    else
        fprintf(['Headless mode: main figures were not rendered automatically. ' ...
            'Run render_cylinder1dm() in desktop MATLAB.\n']);
    end
    reportFile = fullfile(testDir, 'DEMO1234_STAGE_REPORT.md');
else
    generate_broadband_report(stage, figureDir, testDir, 'report');
    if usejava('desktop')
        render_cylinder1dm('broadband');
    else
        fprintf(['Headless mode: broadband figures were not rendered automatically. ' ...
            'Run render_cylinder1dm(''broadband'') in desktop MATLAB.\n']);
    end
    reportFile = fullfile(testDir, 'BROADBAND_CYLINDER1DM_REPORT.md');
end

fprintf('\nStage MAT: %s\n', stageFile);
fprintf('Stage report: %s\n', reportFile);
end

function runner = runner_for_demo(demo)
switch demo
    case 'demo1'
        runner = @controller_demo1;
    case 'demo2'
        runner = @controller_demo2;
    case 'demo3'
        runner = @controller_demo3;
    case 'demo4'
        runner = @controller_demo4;
    case 'demo5'
        runner = @controller_demo5;
    case 'demo5_imc'
        runner = @controller_imc_fxlms;
    otherwise
        error('run_cylinder1dm_stage:UnknownDemo', 'Unknown demo: %s', demo);
end
end

function [stable, value] = stability_status(result)
stable = true;
value = NaN;
switch result.demo
    case 'demo1'
        if isfield(result.extra.design, 'closed_loop_radius')
            value = max(result.extra.design.closed_loop_radius, ...
                result.extra.design.controller_radius);
            stable = value < 1;
        end
    case 'demo2'
        value = result.extra.max_eig_Acl;
        if isfield(result.extra, 'max_eig_T12')
            value = max(value, result.extra.max_eig_T12);
        end
        stable = value < 1;
    case 'demo3'
        if isfield(result.extra, 'F_den')
            value = max(abs(roots(result.extra.F_den)));
            stable = value < 1;
        end
    case 'demo4'
        value = max(result.extra.design.closed_loop_radius, ...
            result.extra.design.controller_radius);
        stable = value < 1;
    case 'demo5'
        stable = result.extra.numeric_failure_count == 0 ...
            && all(isfinite([result.supp_db, result.extra.u_demand_max])) ...
            && ~result.extra.frequency_bound_hit;
        value = double(stable);
    case 'imc_fxlms'
        stable = result.extra.numeric_failure_count == 0 ...
            && all(isfinite([result.supp_db, result.extra.u_demand_max]));
        value = double(stable);
end
end

%% ========================================================================
% 候选调参：在校准信号上为每个 Demo/场景选出冻结参数
%% ========================================================================

function [selections, tuningTable] = tune_demo1234_controllers(calibrationSignals, scope)
specs = tuning_specs();
isBroadband = strcmp({specs.test}, 'T3');
if strcmp(scope, 'broadband')
    specs = specs(isBroadband);
else
    specs = specs(~isBroadband);
end
rowData = cell(0, 12);
selections = repmat(struct( ...
    'demo', '', 'test', '', 'variant', '', 'candidate', '', ...
    'params', struct(), 'calibration_result', struct(), ...
    'feasible', false), numel(specs), 1);

for specIndex = 1:numel(specs)
    spec = specs(specIndex);
    candidateResults = cell(numel(spec.candidates), 1);
    scores = -inf(numel(spec.candidates), 1);
    feasible = false(numel(spec.candidates), 1);

    fprintf('\n--- Tune %s/%s/%s ---\n', spec.demo, spec.variant, spec.test);
    for candidateIndex = 1:numel(spec.candidates)
        candidate = spec.candidates{candidateIndex};
        errorMessage = '';
        try
            result = spec.runner(calibrationSignals, spec.test, ...
                spec.variant, candidate.params);
            [feasible(candidateIndex), stable] = is_feasible(result);
            scores(candidateIndex) = candidate_score(result, ...
                feasible(candidateIndex), stable);
            candidateResults{candidateIndex} = result;
            rowData(end+1, :) = {spec.demo, spec.variant, spec.test, ...
                candidate.name, false, feasible(candidateIndex), stable, ...
                result.supp_db, result.extra.u_demand_max, ...
                result.extra.saturation_count, jsonencode(candidate.params), ''}; %#ok<AGROW>
        catch exception
            errorMessage = exception.message;
            rowData(end+1, :) = {spec.demo, spec.variant, spec.test, ...
                candidate.name, false, false, false, NaN, NaN, NaN, ...
                jsonencode(candidate.params), errorMessage}; %#ok<AGROW>
        end
        if isempty(errorMessage)
            fprintf('  %-18s supp=%7.2f dB raw=%6.3f sat=%d feasible=%d\n', ...
                candidate.name, result.supp_db, result.extra.u_demand_max, ...
                result.extra.saturation_count, feasible(candidateIndex));
        else
            fprintf('  %-18s ERROR %s\n', candidate.name, errorMessage);
        end
    end

    feasibleIndices = find(feasible);
    if isempty(feasibleIndices)
        [~, selectedIndex] = max(scores);
    else
        [~, localIndex] = max(scores(feasibleIndices));
        selectedIndex = feasibleIndices(localIndex);
    end

    selectedCandidate = spec.candidates{selectedIndex};
    selections(specIndex).demo = spec.demo;
    selections(specIndex).test = spec.test;
    selections(specIndex).variant = spec.variant;
    selections(specIndex).candidate = selectedCandidate.name;
    selections(specIndex).params = selectedCandidate.params;
    selections(specIndex).calibration_result = candidateResults{selectedIndex};
    selections(specIndex).feasible = feasible(selectedIndex);

    rowsForSpec = strcmp(rowData(:, 1), spec.demo) ...
        & strcmp(rowData(:, 2), spec.variant) ...
        & strcmp(rowData(:, 3), spec.test);
    rowIndices = find(rowsForSpec);
    rowData{rowIndices(selectedIndex), 5} = true;
end

tuningTable = cell2table(rowData, 'VariableNames', { ...
    'demo', 'variant', 'test', 'candidate', 'selected', 'feasible', ...
    'stable', 'suppression_db', 'control_demand_max', ...
    'saturation_count', 'params_json', 'error_message'});
end

