function comparison = compare_demo2_t2_adaptation(calibrationSignals, evaluationSignals, ~, ~)
base = struct( ...
    'Q_lqr', 1, ...
    'R_lqr', 1e-2, ...
    'Qn_plant', 1e-4, ...
    'Qn_dist', 0.1, ...
    'Rn', 0.1, ...
    'control_scale', 1, ...
    'ramp_seconds', 0.1, ...
    'bp_band', [280 440], ...
    'adaptive_warmup_seconds', 0.5, ...
    'theta_norm_limit', 8, ...
    'nQ', 32, ...
    'adaptation_method', 'lms', ...
    'lms_epsilon', 1e-6, ...
    'lms_leakage', 0);

stepSizes = [0.001, 0.003, 0.01, 0.03, 0.1];
rows = cell(numel(stepSizes), 10);
scores = -inf(numel(stepSizes), 1);
feasible = false(numel(stepSizes), 1);
calibrationResults = cell(numel(stepSizes), 1);

for index = 1:numel(stepSizes)
    params = base;
    params.adaptation_gain = stepSizes(index);
    candidateName = sprintf('lms_n32_mu%g', stepSizes(index));
    try
        result = controller_demo2(calibrationSignals, 'T2', 'adaptive', params);
        calibrationResults{index} = result;
        stable = stability_status(result);
        feasible(index) = stable ...
            && result.extra.u_demand_max <= 4 ...
            && result.extra.saturation_count == 0;
        local = finite_local_suppression(result);
        worstLocal = min(local);
        meanLocal = mean(local);
        scores(index) = 0.5 * worstLocal + 0.5 * meanLocal ...
            - 8 * max(0, result.extra.u_demand_max - 4) ...
            - 0.02 * result.extra.saturation_count ...
            - 100 * double(~stable);
        rows(index, :) = {candidateName, false, feasible(index), stable, ...
            result.supp_db, worstLocal, meanLocal, ...
            result.extra.u_demand_max, result.extra.saturation_count, ...
            jsonencode(params)};
    catch exception
        rows(index, :) = {candidateName, false, false, false, ...
            NaN, NaN, NaN, NaN, NaN, jsonencode(params)};
        fprintf('Demo2 LMS %s ERROR: %s\n', candidateName, exception.message);
    end
end

feasibleIndices = find(feasible);
if isempty(feasibleIndices)
    [~, selectedIndex] = max(scores);
else
    [~, localIndex] = max(scores(feasibleIndices));
    selectedIndex = feasibleIndices(localIndex);
end

rows{selectedIndex, 2} = true;
tuning = cell2table(rows, 'VariableNames', { ...
    'candidate', 'selected', 'feasible', 'stable', ...
    'suppression_db', 'worst_local_suppression_db', ...
    'mean_local_suppression_db', 'control_demand_max', ...
    'saturation_count', 'params_json'});

selectedParams = base;
selectedParams.adaptation_gain = stepSizes(selectedIndex);
lmsEvaluation = controller_demo2(evaluationSignals, 'T2', 'adaptive', selectedParams);

rlsParams = rmfield(base, {'adaptation_method', 'lms_epsilon', 'lms_leakage'});
rlsParams.nQ = 32;
rlsParams.lambda = 0.98;
rlsParams.F_init = 0.1;
rlsParams.adaptation_gain = 0.15;
rlsParams.adaptation_method = 'rls';
rlsCalibration = controller_demo2(calibrationSignals, 'T2', 'adaptive', rlsParams);
rlsEvaluation = controller_demo2(evaluationSignals, 'T2', 'adaptive', rlsParams);

comparison = struct();
comparison.rls = struct( ...
    'candidate', 'q32_l98_g15', ...
    'params', rlsParams, ...
    'calibration', rlsCalibration, ...
    'evaluation', rlsEvaluation);
comparison.lms = struct( ...
    'candidate', tuning.candidate{selectedIndex}, ...
    'params', selectedParams, ...
    'calibration', calibrationResults{selectedIndex}, ...
    'evaluation', lmsEvaluation, ...
    'feasible', feasible(selectedIndex));
comparison.tuning = tuning;
comparison.selection_basis = 'calibration worst/mean local T2 suppression with control constraints';
end

function local = finite_local_suppression(result)
local = result.supp_breakdown.supp_db;
local = local(isfinite(local));
if isempty(local)
    local = -inf;
end
end
